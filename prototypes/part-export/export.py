#!/usr/bin/env python3
"""
export.py — prototype of the app's "Export parts" button.

Reads band.json (the arrangement + who plays what, and how they like to read),
writes one LilyPond file containing a full score plus a part for every player,
then runs LilyPond if it's installed.

Usage:  python3 export.py [band.json]
Output: <title>-score.pdf, <title>-guitar-jeff.pdf, <title>-bass-sam.pdf, ...
"""
import json, re, shutil, subprocess, sys
from pathlib import Path


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def chord_names():
    return "    \\new ChordNames \\harmony\n"


def notation_staff(p, with_structure=True):
    layers = "\\global " + ("\\structure " if with_structure else "")
    return (f'    \\new Staff \\with {{ instrumentName = "{p["name"]}" }}\n'
            f'      << {{ \\clef "{p["clef"]}" {layers}}} \\{p["music"]} >>\n')


def tab_staff(p, full_notation=False):
    # Tab-only readers get rhythms (stems/beams) and section labels on the tab itself.
    if full_notation:
        body = f"<< \\global \\structure {{ \\tabFullNotation \\{p['music']} }} >>"
    else:
        body = f"\\{p['music']}"
    name = f' instrumentName = "{p["name"]}"' if full_notation else ""
    return (f"    \\new TabStaff \\with {{ stringTunings = #{p['tuning']}{name} }}\n"
            f"      {body}\n")


def piano_staff(p, with_structure=True):
    rh, lh = p["piano"]
    s = "\\structure " if with_structure else ""
    return (f'    \\new PianoStaff \\with {{ instrumentName = "{p["name"]}" }} <<\n'
            f'      \\new Staff << {{ \\clef treble \\global {s}}} \\{rh} >>\n'
            f'      \\new Staff << {{ \\clef bass \\global }} \\{lh} >>\n'
            f'    >>\n')


def staves_for(p, fmt):
    """Build the staves for one part in the reader's preferred format."""
    if "piano" in p:
        return piano_staff(p)
    if fmt == "tab":
        return tab_staff(p, full_notation=True)
    if fmt == "notation+tab":
        return notation_staff(p) + tab_staff(p)
    return notation_staff(p)  # "notation"


def book(suffix, instrument, staves, compress_rests):
    compress = "\\compressMMRests " if compress_rests else ""
    return (f"\\book {{\n"
            f'  \\bookOutputSuffix "{suffix}"\n'
            f'  \\header {{ instrument = "{instrument}" }}\n'
            f"  \\score {{\n"
            f"  {compress}<<\n"
            f"{staves}"
            f"  >>\n"
            f"  \\layout {{ }}\n"
            f"  }}\n"
            f"}}\n\n")


def build(cfg):
    parts, players = cfg["parts"], cfg["players"]
    out = [
        '\\version "2.24.0"\n',
        f'\\include "{cfg["source"]}"\n\n',
        "\\header {\n"
        f'  title = "{cfg["title"]}"\n'
        f'  subtitle = "{cfg.get("subtitle", "")}"\n'
        f'  composer = "{cfg.get("arranger", "")}"\n'
        f'  tagline = "{cfg["title"]} {cfg.get("version", "")} — generated by export.py"\n'
        "}\n\n",
        '\\paper { #(set-paper-size "letter") }\n\n',
    ]

    # Full score: every part in standard notation, full-length rests, chords on top.
    # Section labels go on the top staff only, so they print once.
    score = chord_names()
    for i, p in enumerate(parts.values()):
        first = i == 0
        score += piano_staff(p, first) if "piano" in p else notation_staff(p, first)
    out.append(book("score", "Full Score", score, compress_rests=False))

    # One part per player, in that player's preferred format.
    for pl in players:
        p = parts[pl["part"]]
        staves = (chord_names() if p.get("chords") else "") + staves_for(p, pl["format"])
        suffix = f"{pl['part']}-{slug(pl['name'])}"
        out.append(book(suffix, f"{p['name']} — {pl['name']}", staves, compress_rests=True))

    return "".join(out)


def main():
    cfg_path = Path(sys.argv[1] if len(sys.argv) > 1 else "band.json")
    cfg = json.loads(cfg_path.read_text())
    ly_path = cfg_path.with_name(slug(cfg["title"]) + ".ly")
    ly_path.write_text(build(cfg))
    print(f"Wrote {ly_path}")

    if shutil.which("lilypond"):
        subprocess.run(["lilypond", ly_path.name], cwd=ly_path.parent, check=True)
        print("PDFs written next to", ly_path.name)
    else:
        print("LilyPond not found — install it, then run:  lilypond", ly_path.name)


if __name__ == "__main__":
    main()
